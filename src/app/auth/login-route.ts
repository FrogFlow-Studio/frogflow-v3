/**
 * Куда ведёт вход с общей формы, если логин совпал с логином оператора.
 *
 * Логин магазина может совпасть с логином оператора: /signup не отказывает
 * в таком имени, потому что отказ «логин занят» выдал бы логин оператора
 * любому, кто перебирает имена. Раньше такой продавец не мог войти вовсе:
 * имя уходило в ветку оператора, а его попытки считались неудачами
 * оператора и запирали вход оператора с его адреса.
 *
 * Теперь: пароль оператора — панель оператора; пароль магазина с тем же
 * логином — обычный вход продавца, неудачей оператора он не считается;
 * иначе — неудача оператора, как раньше.
 */
export type OperatorNameRoute = "operator" | "shop" | "denied";

export async function routeOperatorName(check: {
  operator: () => Promise<boolean>;
  shop: () => Promise<boolean>;
}): Promise<OperatorNameRoute> {
  if (await check.operator()) return "operator";
  if (await check.shop()) return "shop";
  return "denied";
}
