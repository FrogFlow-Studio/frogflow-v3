export type LandingT = (key: LandingKey, vars?: Record<string, string | number>) => string;

/** Переводчик главной: ключ → строка с подстановкой `{name}`; нет перевода — русский. */
export function landingT(locale: Locale): LandingT {
  const dict = DICTS[locale] ?? ru;
  return (key, vars) => {
    let s = dict[key] ?? ru[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}
