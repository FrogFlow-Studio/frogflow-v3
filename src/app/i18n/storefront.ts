const DICTS: Record<Locale, Dict> = { ru, kk, en, uz };

export type StorefrontT = (key: StorefrontKey, vars?: Record<string, string | number>) => string;

/** Переводчик витрины: ключ → строка с подстановкой `{name}`; нет перевода — русский. */
export function storefrontT(locale: Locale): StorefrontT {
  const dict = DICTS[locale] ?? ru;
  return (key, vars) => {
    let s = dict[key] ?? ru[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

/** Слово «отзыв» в нужной форме для числа — по правилам множественного числа языка. */
export function reviewsWord(locale: Locale, n: number): string {
  const t = storefrontT(locale);
  let form = "other";
  try {
    form = new Intl.PluralRules(intlLocale(locale)).select(n);
  } catch {
    /* нет данных Intl — общая форма */
  }
  if (form === "one") return t("product.reviews.one");
  if (form === "few") return t("product.reviews.few");
  if (form === "many") return t("product.reviews.many");
  return t("product.reviews.other");
}

