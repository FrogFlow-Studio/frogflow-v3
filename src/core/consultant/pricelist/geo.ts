/** Покупатель из России по его словам (перенос src/lib/consultant-v2/geo.ts v1). */
/**
 * Покупатель из России — по его же словам.
 *
 * 27.09, живой диалог BOVI: «Подскажите стоимость доставки в Москву?» — модель
 * ответила про СДЭК, но страну не запомнила (remember_customer не вызвала), и
 * следующие ответы клиентке из Москвы ушли в тенге, а в карточке менеджеру не
 * было ни города, ни страны. Слово «Россия» код ловил и раньше (currency.ts),
 * город — нет. Здесь крупные города России в тех формах, в каких их пишут в
 * вопросе о доставке: «в Москву», «из Питера», «по Подмосковью».
 */

const B = "(?<![а-яёa-z])";
const E = "(?![а-яё])";

const CITIES: [RegExp, string][] = (
  [
    ["москв|московск|подмосков", "Москва"],
    [`санкт-петербург|петербург|питер(?:а|е|у|ом)?${E}|спб${E}`, "Санкт-Петербург"],
    ["новосибирск", "Новосибирск"],
    [`екатеринбург|екб${E}`, "Екатеринбург"],
    [`казан(?:ь|и)${E}`, "Казань"],
    ["нижн[а-яё]*\\s+новгород", "Нижний Новгород"],
    ["краснодар", "Краснодар"],
    [`самар(?:а|у|е|ы)${E}`, "Самара"],
    ["омск", "Омск"],
    ["томск", "Томск"],
    ["челябинск", "Челябинск"],
    ["ростов", "Ростов-на-Дону"],
    [`уф(?:а|у|е|ы)${E}`, "Уфа"],
    ["красноярск", "Красноярск"],
    [`перм(?:ь|и)${E}`, "Пермь"],
    ["воронеж", "Воронеж"],
    ["волгоград", "Волгоград"],
    ["тюмен", "Тюмень"],
    [`сочи${E}`, "Сочи"],
    ["калининград", "Калининград"],
    ["саратов", "Саратов"],
    ["барнаул", "Барнаул"],
    ["иркутск", "Иркутск"],
    ["владивосток", "Владивосток"],
    ["хабаровск", "Хабаровск"],
    ["оренбург", "Оренбург"],
    ["астрахан", "Астрахань"],
    ["ярославл", "Ярославль"],
  ] as const
).map(([stem, city]) => [new RegExp(`${B}(?:${stem})`, "i"), city]);

const RUSSIA_RE = new RegExp(`${B}(?:росси(?:я|ю|и|ей)${E}|рф${E})`, "i");

/**
 * Казахстан рядом («я в Алматы, отправить в Москву») — кто покупатель, неясно:
 * страну не угадываем.
 */
const KAZAKHSTAN_RE = new RegExp(
  `${B}(?:казахстан|алмат|астан|шымкент|караганд|актоб|атырау|актау|павлодар|костанай|тараз|кызылорд|уральск|талдыкорган|туркестан|экибастуз|усть-каменогорск)`,
  "i",
);

/** Россия и город, если покупатель их назвал; иначе null. */
export function russianPlaceIn(text: string): { country: "Россия"; city?: string } | null {
  if (!text || KAZAKHSTAN_RE.test(text)) return null;
  const city = CITIES.find(([re]) => re.test(text))?.[1];
  if (city) return { country: "Россия", city };
  return RUSSIA_RE.test(text) ? { country: "Россия" } : null;
}
