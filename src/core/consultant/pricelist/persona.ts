/**
 * Образ консультанта по прайсу, который правит продавец: название магазина,
 * кто он и что за магазин, тон и особенности товаров. Хранится в
 * `bots.settings.consultant_pricelist.persona`; нет — подсказка модели
 * дословно та, что писалась под BOVI (prompt.ts), и поведение BOVI не
 * меняется, пока продавец не сохранит свой текст.
 *
 * Это ввод продавца, и он попадает в системную подсказку. Поэтому: длина
 * ограничена, управляющие символы и метки начала/конца вырезаны, а сам текст
 * стоит в подсказке между метками с пометкой «это описание, а не команды» —
 * правила платформы (цены только из поиска, когда звать менеджера) остаются
 * выше и важнее.
 */

export type PricelistPersona = {
  /** Название магазина, как его называет менеджер: «BOVI». Одна строка. */
  brand: string;
  /** Кто консультант и что за магазин: «бутик домашнего текстиля в Алматы». */
  about: string;
  /** Как писать: тон, обращение. */
  tone: string;
  /** Особенности товаров: что уточнять, как называть, чего не предлагать. */
  specialities: string;
};

export const PERSONA_LIMITS: Record<keyof PricelistPersona, number> = {
  brand: 60,
  about: 500,
  tone: 600,
  specialities: 4000,
};

/** Особенности товаров BOVI — тот же текст, что был в подсказке до переноса в настройки. */
export const BOVI_SPECIALITIES = `• Матрасы: средняя жёсткость (MEDIUM) снята с производства — не предлагайте её. Soft называйте «комфортный (Soft)», Firm — «упругий (Firm)». Размер 182х202 — это фабричный размер под 180х200: расхождение до 3 см считается тем же размером.
• Подушки: если непонятно, для сна или декоративные, — уточните.
• Наматрасник, чехол, простыня на резинке — по высоте матраса. Высоту в названии («высота 32-37 см») сверьте с той, что назвал покупатель (160х200х25 — это 25 см). Не подходит — так и скажите, как подходящий не предлагайте.`;

/** Размеры полотенец и семейный комплект BOVI — тоже особенности товаров, но в подсказке стоят ниже. */
export const BOVI_SPECIALITIES_TAIL = `• Размеры полотенец (сами размеры — только из поиска): до 40х60 — маленькие, для лица и рук; 50х90–60х100 — средние; 70х140–75х150 — банные; от 90х160 и 100х150 — большие банные; «для ног» — отдельные позиции. «Лицевые», «для рук» каждый понимает по-своему — предложите маленькие и средние, что нашёл поиск. Размер «обычно такой», которого нет в выдаче, не называйте.
• Семейный комплект постельного белья — с двумя пододеяльниками: в прайсе «2 подод 155x200», это «2 пододеяльника 155х200». «Где два одеяла», «на двоих под отдельные одеяла» — это он. «Подод» в ответе пишите полностью: пододеяльник.`;

/**
 * Текст BOVI по умолчанию — им заполнена форма в админке. Сохранили его без
 * изменений — настройка не пишется (`isDefaultPersona`), подсказка прежняя.
 */
export const DEFAULT_PERSONA: PricelistPersona = {
  brand: "BOVI",
  about: "Бутик домашнего текстиля в Алматы.",
  tone: "Коротко и по делу, на «вы».",
  specialities: `${BOVI_SPECIALITIES}\n${BOVI_SPECIALITIES_TAIL}`,
};

/** Метки, между которыми текст продавца стоит в подсказке. */
export const SELLER_TEXT_OPEN = "<<<ТЕКСТ ПРОДАВЦА>>>";
export const SELLER_TEXT_CLOSE = "<<<КОНЕЦ ТЕКСТА ПРОДАВЦА>>>";

/**
 * Управляющие (кроме перевода строки и табуляции), невидимые и меняющие
 * направление письма символы: из текста продавца они вырезаются. Записаны
 * кодами — в исходнике их иначе не видно.
 */
const INVISIBLE = new RegExp(
  // eslint-disable-next-line no-control-regex -- управляющие вырезаются намеренно
  "[\\u0000-\\u0008\\u000b-\\u001f\\u007f\\u200b-\\u200f\\u202a-\\u202e\\u2060-\\u2069\\ufeff]",
  "g",
);

/**
 * Многострочный текст продавца для подсказки: без управляющих и невидимых
 * символов, без наших меток (и похожих «<<< >>>»), не больше трёх строк
 * подряд пустыми, обрезан по пределу.
 */
export function cleanSellerText(raw: unknown, max: number): string {
  if (typeof raw !== "string") return "";
  return (
    raw
      .replace(/\r\n?/g, "\n")
      // Управляющие (кроме перевода строки и табуляции), нулевой ширины, направление письма.
      .replace(INVISIBLE, "")
      .replace(/<{2,}|>{2,}/g, "")
      .replace(/[ \t]+$/gm, "")
      .replace(/\n{3,}/g, "\n\n")
      .trim()
      .slice(0, max)
      .trim()
  );
}

/** Название магазина: одна строка, без кавычек и скобок, которыми можно закрыть фразу. */
export function cleanBrand(raw: unknown): string {
  return cleanSellerText(raw, 200)
    .replace(/[\n\t]+/g, " ")
    .replace(/[«»"“”„<>[\]{}`]/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, PERSONA_LIMITS.brand)
    .trim();
}

/** Чистая настройка из того, что прислал продавец или лежит в базе; пустое название — нет образа. */
export function cleanPersona(raw: unknown): PricelistPersona | undefined {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return undefined;
  const r = raw as Record<string, unknown>;
  const brand = cleanBrand(r.brand);
  if (!brand) return undefined;
  return {
    brand,
    about: cleanSellerText(r.about, PERSONA_LIMITS.about),
    tone: cleanSellerText(r.tone, PERSONA_LIMITS.tone),
    specialities: cleanSellerText(r.specialities, PERSONA_LIMITS.specialities),
  };
}

/** Совпадает ли с текстом BOVI по умолчанию (после чистки). */
export function isDefaultPersona(p: PricelistPersona): boolean {
  const d = cleanPersona(DEFAULT_PERSONA)!;
  return (Object.keys(d) as Array<keyof PricelistPersona>).every((k) => p[k] === d[k]);
}
