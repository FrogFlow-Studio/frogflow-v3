/**
 * Промпт консультанта v2 (ИИ-менеджер BOVI).
 *
 * В v1 правила росли на каждую жалобу и дошли до 39 тысяч знаков: модель
 * читала двадцать страниц запретов, половина из которых писалась под
 * конкретный сбой. Здесь — роль, цель, как писать, как продавать и факты
 * магазина. Остальное модель берёт из данных: прайс, база знаний,
 * инструменты. Правило добавляется сюда, только если без него модель
 * ошибается на эталонном наборе, а не на одной жалобе.
 *
 * Стиль задан примерами живого менеджера BOVI: из её ответов в директе видно,
 * как здесь пишут — «50*100 и 70*140», «Коврик 35*50=6400 руб».
 */

