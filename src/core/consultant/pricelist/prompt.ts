/** Марка — латиница в начале названия: «Bedding House PIP», «Uchino», «Kleen-tex». */
function brandOf(name: string): string {
  const prefix = /^[^А-Яа-яЁё]*/.exec(name.trim())?.[0] ?? "";
  return prefix
    .replace(/[^A-Za-z0-9&.' -]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 30);
}

/** Вид товара — первое русское слово названия: «полотенце», «подушка», «КПБ». */
function kindOf(name: string): string {
  const word = /[А-Яа-яЁё]{3,}/.exec(name)?.[0] ?? "";
  if (word === "КПБ") return "комплект постельного белья";
  return word.toLowerCase();
}

/**
 * Раздел 1С без латинских слов, которых нет в названии позиции.
 *
 * В 1С коврик Aquanova Maks лежит в разделе «Коврики LONDON», и 25.09 бот
 * дважды назвал серией London три размера — 60х100, 70х120 и 60х60, — хотя
 * 60х60 это Maks. Латиница в разделе — серия или марка; если у позиции её в
 * названии нет, это не её серия: «Коврики LONDON» у Maks → «Коврики».
 * Раздел из одной латиницы («Loft», «Castelbel») остаётся как есть.
 */
export function categoryOf(product: Pick<ConsultantProduct, "name" | "category">): string {
  const category = product.category?.trim() ?? "";
  const name = product.name.toLowerCase();
  const cleaned = category
    .replace(/[A-Za-z][A-Za-z-]*/g, (word) => (name.includes(word.toLowerCase()) ? word : ""))
    .replace(/\(\s*\)/g, "")
    .replace(/\s+/g, " ")
    .trim();
  // От раздела должно остаться русское слово вне скобок: «ROYAL CROWN DERBY
  // (Англия)» у блюдца RCD не превращается в «(Англия)».
  return /[А-Яа-яЁё]/.test(cleaned.replace(/\([^)]*\)/g, "")) ? cleaned : category;
}

function topValues(values: string[], limit: number): string {
  const count = new Map<string, number>();
  for (const v of values) if (v.trim()) count.set(v.trim(), (count.get(v.trim()) ?? 0) + 1);
  const sorted = [...count].sort((a, b) => b[1] - a[1]).map(([v]) => v);
  return sorted.length > limit ? `${sorted.slice(0, limit).join(", ")} и др.` : sorted.join(", ");
}

/**
 * Карта ассортимента для промпта v2 — вместо полного прайса.
 *
 * 25.09, тест v2 на Haiku 4.5: с прайсом на 791 строку в промпте модель
 * брала цену соседней строки (Swing Light за 50 000 — цена Swing Extra Light,
 * пуховая Soft за 85 000 — цена Medium) и выкладывала списки на широкий
 * вопрос. Здесь по строке на раздел: что за товары, чьи, каких размеров и от
 * какой цены. Этого хватает, чтобы ответить «что есть»; позиции и цены
 * модель берёт поиском — из короткой выдачи, где путать нечего.
 */
export function formatAssortmentMapForV2(catalog: ConsultantProduct[]): string {
  const inStock = catalog.filter((p) => p.stock);
  if (inStock.length === 0) return "КАРТА АССОРТИМЕНТА: сейчас пусто.";
  // Строка — раздел и вид товара: в разделе «Подушки Dorelan» есть и
  // наволочка за 35 000, и «от 35 000» на весь раздел модель 25.09 назвала
  // ценой подушки (они от 85 000).
  const groups = new Map<string, ConsultantProduct[]>();
  for (const p of inStock) {
    const key = `${categoryOf(p) || "Без раздела"}\u0000${kindOf(p.name) || "товары"}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key)!.push(p);
  }
  const lines = [
    "КАРТА АССОРТИМЕНТА — всё в наличии. Раздел — вид товара (марки): число позиций; размеры; цена от.",
    "Конкретных позиций, цен и расцветок здесь нет: их даёт поиск search_products.",
  ];
  for (const [key, products] of [...groups].sort((a, b) => a[0].localeCompare(b[0], "ru"))) {
    const [category, kinds] = key.split("\u0000");
    const brands = topValues(
      products.map((p) => brandOf(p.name)),
      4,
    );
    // «240х220» и «240x220» — один размер: в прайсе пишут по-разному.
    const sizeOf = (p: ConsultantProduct) =>
      p.size.replace(/(\d)\s*[xхХ×*]\s*(\d)/g, "$1x$2").trim();
    const bySize = new Map<string, number>();
    for (const p of products) {
      const size = sizeOf(p);
      if (size && p.price_kzt > 0)
        bySize.set(size, Math.min(bySize.get(size) ?? Infinity, p.price_kzt));
    }
    const from = Math.min(...products.map((p) => p.price_kzt).filter((n) => n > 0));
    const parts = [
      `• ${category} — ${kinds}${brands ? ` (${brands})` : ""}: ${products.length} поз.`,
    ];
    if (bySize.size > 1 && bySize.size <= 4 && products.every((p) => sizeOf(p))) {
      // Несколько размеров — цена «от» у каждого: «от 30 000» на весь раздел
      // модель приписывала размеру 50х70, а 30 000 стоит только 40х60.
      parts.push(
        [...bySize].map(([size, min]) => `${size} от ${min.toLocaleString("ru-RU")} ₸`).join(", "),
      );
    } else {
      const sizes = topValues(products.map(sizeOf), 6);
      if (sizes) parts.push(`размеры ${sizes}`);
      if (Number.isFinite(from)) parts.push(`от ${from.toLocaleString("ru-RU")} ₸`);
    }
    lines.push(parts.join("; "));
  }
  return lines.join("\n");
}

