/**
 * Оптовый запрос — сразу менеджеру, до модели (перенос v1 consultant/intent.ts:97,
 * handle-message.ts:858). Выгрузка v1 19–22.09: «У вас можно оптом закуп
 * сделать?» и «У вас опт есть?» — бот показал анкету про страну, оба ушли.
 * Оптового прайса, партий и условий у консультанта нет, любой его ответ —
 * выдумка.
 *
 * Форма слова проверяется до конца: голое «опт» подстрокой сидит в
 * «оптимально» и «оптика».
 */
const WHOLESALE_RE =
  /опт(?:ов[а-яё]+|ом|ах?|у|е)?(?![а-яё])|дилер|дистриб[а-яё]*|перепрода[а-яё]*|(^|[^a-zа-яё])b2b([^a-zа-яё]|$)|мелким\s+опт/i;

export function matchWholesaleIntent(text: string): boolean {
  return WHOLESALE_RE.test((text ?? "").trim());
}
