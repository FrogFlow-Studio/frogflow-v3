import { describe, expect, it } from "vitest";
import { isPaidReport } from "./paid-report";

describe("isPaidReport — сообщение об оплате, а не вопрос", () => {
  it.each([
    "Оплатила",
    "Я оплатила",
    "Оплатила на каспи 1700",
    "Перевела 1400 на каспи",
    "заплатил",
    "Скинула деньги",
    "Отправила оплату",
    "Төледім",
    "To'ladim",
    "I paid",
  ])("«%s» — об оплате", (t) => expect(isPaidReport(t)).toBe(true));

  it.each([
    "А этот материал точно придёт? Боюсь мошенников",
    "Почему сейчас надо платить, а не при получении?",
    "Карточки поощрений тоже. Вместе сколько будет",
    "Я ещё не отправила деньги. Хочу приобрести и другие материалы",
    "Не оплатила пока",
    "Оплатила?",
    "Куда вышлет материалы",
    "Спасибо",
  ])("«%s» — не об оплате", (t) => expect(isPaidReport(t)).toBe(false));
});
